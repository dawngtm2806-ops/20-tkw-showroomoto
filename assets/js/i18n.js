  function curLang() { try { return localStorage.getItem('sr_lang') || 'vi'; } catch (e) { return 'vi'; } }

  S.lang = curLang;
  S.t = function (key, fallback) {
    var l = curLang();
    return (DICT[l] && DICT[l][key]) || DICT.vi[key] || fallback || key;
  };

  // Dịch các phần tử HTML tĩnh có data-i18n / data-i18n-ph
  S.applyI18n = function (root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      var v = S.t(k, el.textContent);
      el.textContent = v;
    });
    root.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', S.t(el.getAttribute('data-i18n-ph'), el.getAttribute('placeholder')));
    });
    document.documentElement.setAttribute('lang', curLang());
  };

